@lru_cache(maxsize=1)
def _demello_modules() -> tuple[Any, Any]:
    root = _asset_root()
    if str(root) not in sys.path:
        sys.path.insert(0, str(root))
    workflow = importlib.import_module("resources.demello_resource.workflow")
    image_gen = importlib.import_module("resources.demello_resource.image_gen")
    return workflow, image_gen


def _canonical_json_bytes(value: Any) -> bytes:
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode()


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _artifact_descriptor(
    root: Path,
    owner_id: str,
    run_id: str,
    access_token: str,
    expires: int,
    source: Path,
    *,
    kind: str,
    content_type: str,
) -> dict[str, Any]:
    scope = owner_scope(owner_id)
    digest = _sha256_file(source)
    filename = source.name
    if not SHA256_RE.fullmatch(digest) or not FILENAME_RE.fullmatch(filename):
        raise ArtifactAccessError("ARTIFACT_DESCRIPTOR_INVALID")
    relative = Path("owners") / scope / "runs" / run_id / digest / filename
    destination = root / relative
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.exists():
        if _sha256_file(destination) != digest:
            raise ArtifactAccessError("ARTIFACT_IMMUTABLE_COLLISION")
    else:
        try:
            os.link(source, destination)
        except OSError:
            shutil.copyfile(source, destination)
    url = (
        f"{PUBLIC_BASE_URL}/v1/artifacts/{scope}/{run_id}/{digest}/{filename}"
        f"?expires={expires}&access_token={access_token}"
    )
    return {
        "kind": kind,
        "object_key": relative.as_posix(),
        "sha256": digest,
        "bytes": destination.stat().st_size,
        "content_type": content_type,
        "url": url,
    }


def _write_access_manifest(
    root: Path,
    owner_id: str,
    run_id: str,
    access_token: str,
    expires: int,
    artifacts: list[dict[str, Any]],
) -> None:
    scope = owner_scope(owner_id)
    manifest = {
        "schema_version": "omo.owner-artifacts/v1",
        "owner_scope": scope,
        "run_id": run_id,
        "access_token_sha256": access_token_sha256(access_token),
        "expires": expires,
        "artifacts": {
            item["object_key"]: {
                "sha256": item["sha256"],
                "bytes": item["bytes"],
                "content_type": item["content_type"],
            }
            for item in artifacts
        },
    }
    path = root / "owners" / scope / "runs" / run_id / "access.json"
    temporary = path.with_name("access.json." + uuid.uuid4().hex + ".tmp")
    temporary.write_bytes(_canonical_json_bytes(manifest))
    os.replace(temporary, path)


def run_sample_pipeline(
    payload: dict[str, Any],
    *,
    owner_id: str,
    run_id: str,
    access_token: str,
    output_root: Path,
    clock: Callable[[], float] = time.time,
) -> dict[str, Any]:
    """Run the pinned sample through the reused reviewed renderer and QA."""
    validate_instance(payload, "input.json")
    if run_id != run_id_for(owner_id, access_token):
        raise ArtifactAccessError("RUN_OWNER_MISMATCH")
    workflow, _image_gen = _demello_modules()
    resource_root = _asset_root() / "resources" / "demello_resource"
    owner_root = output_root / "owners" / owner_scope(owner_id)
    reviewed_request = {
        "audio_ref": SAMPLE_ID,
        "style": STYLE_ID,
        "duration_bounds": {"min_seconds": 10, "max_seconds": 10},
        "run_id": run_id,
        "max_cost_usd": 0.003,
    }
    config = workflow.PipelineConfig(
        artifact_root=owner_root,
        work_root=Path("/tmp/omo-japanese-story-video"),
        audio_refs={SAMPLE_ID: resource_root / "assets" / "sample-demello-10s.m4a"},
        transcript_refs={
            SAMPLE_ID: resource_root / "assets" / "sample-demello-10s.transcript.json"
        },
        allow_procedural_fallback=True,
        anchor_interval_seconds=3,
        guarded_price_usd=PRICE_USD,
        static_estimate_usd=0.003,
    )
    rich = workflow.run_pipeline(reviewed_request, config)
    run_root = owner_root / "runs" / run_id
    transcript = load_json(
        "resources/demello_resource/assets/sample-demello-10s.transcript.json"
    )
    transcript_value = workflow._coerce_transcript(transcript, 10.0)
    frame_brief = workflow.deterministic_director(transcript_value, 10.0)
    generated_frames = rich["image_generation"]["frames"]
    frame_manifest = {
        "schema_version": "japanese.procedural-sumi-e-frames/v1",
        "style": PUBLIC_STYLE,
        "internal_style": STYLE_ID,
        "palette": {"paper": "#FFFFFF", "ink": "#1A1A1A"},
        "width": 1080,
        "height": 1920,
        "semantic_fps": 3,
        "frames": [
            {
                key: frame[key]
                for key in (
                    "frame_id",
                    "second",
                    "parent_frame_id",
                    "prompt_sha256",
                    "image_sha256",
                    "attempts",
                    "visual",
                )
            }
            for frame in generated_frames
        ],
    }
    (run_root / "transcript.json").write_bytes(_canonical_json_bytes(transcript))
    (run_root / "frame-brief.json").write_bytes(_canonical_json_bytes(frame_brief))
    (run_root / "frames.json").write_bytes(_canonical_json_bytes(frame_manifest))
    expires = int(clock()) + ARTIFACT_TTL_SECONDS
    declarations = [
        ("video", "video/mp4", run_root / "video.mp4"),
        ("contact_sheet", "image/jpeg", run_root / "contact-sheet.jpg"),
        ("transcript", "application/json", run_root / "transcript.json"),
        ("frame_brief", "application/json", run_root / "frame-brief.json"),
        ("frame_manifest", "application/json", run_root / "frames.json"),
    ]
    artifacts = [
        _artifact_descriptor(
            output_root,
            owner_id,
            run_id,
            access_token,
            expires,
            path,
            kind=kind,
            content_type=content_type,
        )
        for kind, content_type, path in declarations
    ]
    _write_access_manifest(
        output_root, owner_id, run_id, access_token, expires, artifacts
    )
    result = {
        "run_id": run_id,
        "status": "completed",
        "workflow_version": WORKFLOW_VERSION,
        "artifacts": artifacts,
        "media": {
            key: rich["media"][key]
            for key in (
                "duration_seconds",
                "width",
                "height",
                "fps",
                "video_codec",
                "audio_codec",
            )
        },
        "usage": {
            "generated_frames": len(generated_frames),
            "accepted_frames": len(generated_frames),
            "output_frames": rich["frames_used"]["output"],
            "generation_provider": "procedural-fallback",
            "provider_cost_usd": 0,
        },
    }
    validate_instance(result, "output.json")
    return result


Executor = Callable[[dict[str, Any]], dict[str, Any]]


def execute_workflow(
    payload: dict[str, Any],
    *,
    executor: Executor | None = None,
    owner_id: str = "local-owner",
    run_id: str | None = None,
    access_token: str | None = None,
    artifact_root: Path | None = None,
    clock: Callable[[], float] = time.time,
) -> dict[str, Any]:
    validate_instance(payload, "input.json")
    if executor is not None:
        result = executor(payload)
        validate_instance(result, "output.json")
        return result
    state = readiness()
    if not state["can_submit"]:
        raise WorkflowNotReady("; ".join(item["code"] for item in state["blockers"]))
    token = access_token or secrets.token_urlsafe(32)
    identifier = run_id or run_id_for(owner_id, token)
    root = artifact_root or MEDIA_ARTIFACT_ROOT
    result = run_sample_pipeline(
        payload,
        owner_id=owner_id,
        run_id=identifier,
        access_token=token,
        output_root=root,
        clock=clock,
    )
    if artifact_root is None:
        media_artifact_volume.commit()
    return result


