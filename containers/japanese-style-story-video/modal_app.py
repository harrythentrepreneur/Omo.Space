SpawnRunner = Callable[[dict[str, Any]], str]
LookupResult = Callable[[str], dict[str, Any]]


def create_fastapi_app(
    spawn_runner: SpawnRunner | None = None,
    lookup_result: LookupResult | None = None,
    *,
    ready_override: bool | None = None,
) -> Any:
    from fastapi import Body, FastAPI, Header, HTTPException, Query
    from fastapi.responses import JSONResponse, Response
    from jsonschema import ValidationError

    web = FastAPI(title="japanese-style-story-video", version="0.2.0")

    def default_spawn(envelope: dict[str, Any]) -> str:
        return run_workflow.spawn(envelope).object_id

    def default_lookup(call_id: str) -> dict[str, Any]:
        return modal.FunctionCall.from_id(call_id).get(timeout=0)

    spawn = spawn_runner or default_spawn
    lookup = lookup_result or default_lookup

    @web.post("/v1/runs", status_code=202)
    async def submit(
        body: Any = Body(...),
        x_omo_owner_id: str | None = Header(default=None, alias="X-Omo-Owner-Id"),
    ) -> Any:
        try:
            validate_instance(body, "input.json")
            owner_id = _owner(x_omo_owner_id or "")
        except (ValidationError, ArtifactAccessError) as exc:
            detail = exc.message if isinstance(exc, ValidationError) else "owner_required"
            raise HTTPException(status_code=422, detail=detail) from exc
        state = readiness()
        can_submit = state["can_submit"] if ready_override is None else ready_override
        if not can_submit:
            return JSONResponse(
                {
                    "status": "not_ready",
                    "error": {"code": "WORKFLOW_NOT_READY", "blockers": state["blockers"]},
                },
                status_code=503,
            )
        access_token = secrets.token_urlsafe(32)
        run_id = run_id_for(owner_id, access_token)
        domain_state.create(owner_id, run_id)
        call_id = spawn(
            {
                "input": body,
                "owner_id": owner_id,
                "run_id": run_id,
                "access_token": access_token,
            }
        )
        return {
            "run_id": run_id,
            "call_id": call_id,
            "status": "accepted",
            "phase": "queued",
            "progress_pct": 0,
            "result_url": (
                f"/v1/runs/{run_id}?call_id={call_id}&access_token={access_token}"
            ),
        }

    @web.get("/v1/runs/{run_id}")
    async def get_result(
        run_id: str,
        call_id: str = Query(..., min_length=8, max_length=200),
        access_token: str = Query(..., min_length=32, max_length=200),
        x_omo_owner_id: str | None = Header(default=None, alias="X-Omo-Owner-Id"),
    ) -> Any:
        owner_id = x_omo_owner_id or ""
        try:
            if run_id != run_id_for(owner_id, access_token):
                raise ArtifactAccessError("RUN_OWNER_MISMATCH")
        except ArtifactAccessError as exc:
            raise HTTPException(status_code=404, detail="run_not_found") from exc
        try:
            result = lookup(call_id)
            validate_instance(result, "output.json")
            if result["run_id"] != run_id:
                raise ValueError("run result identity mismatch")
            return result
        except TimeoutError:
            return JSONResponse(
                {"run_id": run_id, "status": "processing", "phase": "rendering"},
                status_code=202,
            )
        except Exception:
            return JSONResponse(
                {"run_id": run_id, "status": "failed", "error": {"code": "RUN_FAILED"}},
                status_code=500,
            )

    @web.get("/v1/artifacts/{scope}/{run_id}/{digest}/{filename}")
    async def get_artifact(
        scope: str,
        run_id: str,
        digest: str,
        filename: str,
        expires: int,
        access_token: str = Query(..., min_length=32, max_length=200),
    ) -> Any:
        try:
            if not re.fullmatch(r"[0-9a-f]{24}", scope):
                raise ArtifactAccessError("ARTIFACT_KEY_INVALID")
            if not RUN_RE.fullmatch(run_id) or not SHA256_RE.fullmatch(digest):
                raise ArtifactAccessError("ARTIFACT_KEY_INVALID")
            if not FILENAME_RE.fullmatch(filename) or expires < int(time.time()):
                raise ArtifactAccessError("ARTIFACT_LINK_EXPIRED")
        except ArtifactAccessError as exc:
            raise HTTPException(status_code=404, detail="artifact_not_found") from exc
        media_artifact_volume.reload()
        access_path = MEDIA_ARTIFACT_ROOT / "owners" / scope / "runs" / run_id / "access.json"
        try:
            access = json.loads(access_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise HTTPException(status_code=404, detail="artifact_not_found") from exc
        relative = (Path("owners") / scope / "runs" / run_id / digest / filename).as_posix()
        evidence = access.get("artifacts", {}).get(relative)
        if (
            access.get("owner_scope") != scope
            or access.get("run_id") != run_id
            or access.get("expires") != expires
            or access.get("access_token_sha256") != access_token_sha256(access_token)
            or not isinstance(evidence, Mapping)
            or evidence.get("sha256") != digest
        ):
            raise HTTPException(status_code=404, detail="artifact_not_found")
        path = MEDIA_ARTIFACT_ROOT / relative
        try:
            data = path.read_bytes()
        except OSError as exc:
            raise HTTPException(status_code=404, detail="artifact_not_found") from exc
        if hashlib.sha256(data).hexdigest() != digest or len(data) != evidence.get("bytes"):
            raise HTTPException(status_code=404, detail="artifact_not_found")
        return Response(
            content=data,
            media_type=str(evidence["content_type"]),
            headers={
                "Cache-Control": "private, no-store",
                "Content-Disposition": f'attachment; filename="{filename}"',
            },
        )

    return web


