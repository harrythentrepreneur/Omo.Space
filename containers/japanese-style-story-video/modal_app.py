class WorkflowNotReady(RuntimeError):
    """Raised before effects when the reviewed sample executor is unavailable."""


class ArtifactAccessError(RuntimeError):
    """Typed owner or exact-object artifact denial."""


class DomainStateError(RuntimeError):
    """Typed owner-scoped run-state failure."""


def _asset_root() -> Path:
    return LOCAL_ROOT if (LOCAL_ROOT / "schemas" / "input.json").is_file() else IMAGE_ROOT


@lru_cache(maxsize=None)
def load_json(relative_path: str) -> dict[str, Any]:
    with (_asset_root() / relative_path).open(encoding="utf-8") as handle:
        value = json.load(handle)
    if not isinstance(value, dict):
        raise ValueError("reviewed JSON asset must contain an object")
    return value


@lru_cache(maxsize=None)
def load_schema(name: str) -> dict[str, Any]:
    schema = load_json(f"schemas/{name}")
    Draft202012Validator.check_schema(schema)
    return schema


def validate_instance(instance: Any, schema_name: str) -> None:
    Draft202012Validator(load_schema(schema_name)).validate(instance)


def readiness() -> dict[str, Any]:
    return load_json("manifest.json")["readiness"]


def _owner(value: str) -> str:
    if not isinstance(value, str) or not OWNER_RE.fullmatch(value):
        raise ArtifactAccessError("OWNER_INVALID")
    return value


def owner_scope(owner_id: str) -> str:
    owner = _owner(owner_id)
    return hashlib.sha256(("omo-owner-v1\0" + owner).encode()).hexdigest()[:24]


def access_token_sha256(access_token: str) -> str:
    if not isinstance(access_token, str) or len(access_token) < 32 or len(access_token) > 200:
        raise ArtifactAccessError("ACCESS_TOKEN_INVALID")
    return hashlib.sha256(("omo-artifact-access-v1\0" + access_token).encode()).hexdigest()


def run_id_for(owner_id: str, access_token: str) -> str:
    owner = _owner(owner_id)
    token_digest = access_token_sha256(access_token)
    digest = hashlib.sha256(
        ("omo-japanese-run-v1\0" + owner + "\0" + token_digest).encode()
    ).hexdigest()
    return "run-" + digest[:32]


class InMemoryDomainState:
    """Generated owner-scoped state seam; hosted work is polled by Modal call ID."""

    def __init__(self, clock: Callable[[], float] = time.time) -> None:
        self._clock = clock
        self._records: dict[str, dict[str, Any]] = {}

    def create(self, owner_id: str, run_id: str, ttl_seconds: int = 3600) -> dict[str, Any]:
        owner = _owner(owner_id)
        if not RUN_RE.fullmatch(run_id) or not 60 <= ttl_seconds <= 86400:
            raise DomainStateError("STATE_INPUT_INVALID")
        if run_id in self._records:
            record = self._records[run_id]
            if record["owner_id"] == owner:
                return self.read_owned(owner, run_id)
            raise DomainStateError("STATE_NOT_FOUND")
        now = float(self._clock())
        self._records[run_id] = {
            "run_id": run_id,
            "owner_id": owner,
            "status": "queued",
            "phase": "queued",
            "progress_pct": 0,
            "created_at": now,
            "updated_at": now,
            "expires_at": now + ttl_seconds,
        }
        return self.read_owned(owner, run_id)

    def transition(
        self, owner_id: str, run_id: str, status: str, phase: str, progress_pct: int
    ) -> dict[str, Any]:
        record = self._owned(owner_id, run_id)
        allowed = {"queued": {"processing"}, "processing": {"done", "blocked"}}
        if status not in allowed.get(record["status"], set()):
            raise DomainStateError("STATE_TRANSITION_INVALID")
        if not isinstance(progress_pct, int) or progress_pct < record["progress_pct"]:
            raise DomainStateError("STATE_PROGRESS_INVALID")
        if status == "done" and progress_pct != 100:
            raise DomainStateError("STATE_PROGRESS_INVALID")
        record.update(
            status=status,
            phase=str(phase)[:80],
            progress_pct=progress_pct,
            updated_at=float(self._clock()),
        )
        return self.read_owned(owner_id, run_id)

    def _owned(self, owner_id: str, run_id: str) -> dict[str, Any]:
        owner = _owner(owner_id)
        record = self._records.get(run_id)
        if record is None or record["owner_id"] != owner:
            raise DomainStateError("STATE_NOT_FOUND")
        if float(self._clock()) >= record["expires_at"]:
            raise DomainStateError("STATE_EXPIRED")
        return record

    def read_owned(self, owner_id: str, run_id: str) -> dict[str, Any]:
        record = self._owned(owner_id, run_id)
        return {
            key: value
            for key, value in record.items()
            if key != "owner_id"
        }


